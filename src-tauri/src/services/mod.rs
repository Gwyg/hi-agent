//! 服务层:用例编排。
//!
//! 分层自上而下,单向依赖:
//! - `commands/`(对外接口层):只做翻译——invoke 参数 ↔ 用例调用,
//!   `AgentEvent` ↔ Tauri IPC 事件。不含业务逻辑;
//! - `services/`(本层):把一个"用户意图"编排成完整流程——装配依赖、加锁、
//!   跑循环、收敛错误。下层各模块彼此不认识,用例在这里被组装;
//! - 下层:`ai/`(本项目特有的能力——agent 循环、LLM 客户端/消息/工具)、
//!   `config/`(配置,任何项目都要有)、`util/`(横切基础原语)。
//!   它们都与用例无关,不感知服务层与命令层的存在。
//!
//! 命令层到下层**只经本层**:ai 层对命令层只开一扇门(用例函数)。
//! 新增能力时:`ai/` 加实现 → 本层加用例 → 命令层加转发,三层各自单向前依赖。

